            modifier = Modifier
                .fillMaxSize()
                .background(
                    Brush.radialGradient(
                        colors = listOf(animatedStageColor, Color.Transparent),
                        radius = 1200f
                    )
                )
        )

        Scaffold(
            containerColor = Color.Transparent,
            bottomBar = {
                AnimatedCurvedNavigationBar(
                    tabs = APP_TABS,
                    selectedTabId = selectedTab,
                    onTabSelected = { selectedTab = it }
                )
            }
        ) { paddingValues ->
            Column(
                modifier = Modifier
                    .fillMaxSize()
                    .padding(paddingValues)
            ) {
                // Top App Bar
                TopBar()

                // Content for current tab
                Box(modifier = Modifier.fillMaxSize()) {
                    when (selectedTab) {
                        "home" -> HomeScreen(
                            totalGenerated = totalGenerated,
                            surah = currentSurah,
                            ayah = currentAyah,
                            onNavigateToStudio = { selectedTab = "studio" },
                            onNavigateToSchedule = { selectedTab = "schedule" },
                            onNavigateToLibrary = { selectedTab = "library" }
                        )
                        "studio" -> StudioScreen(
                            surah = currentSurah,
                            ayah = currentAyah,
                            isGenerating = isGenerating,
                            progress = generationProgress,
                            onGenerate = {
                                scope.launch {
                                    isGenerating = true
                                    generationProgress = 0f
                                    for (step in 1..10) {
                                        delay(250)
                                        generationProgress = step / 10f
                                    }
                                    isGenerating = false
                                    totalGenerated++
                                    currentAyah += 2
                                }
                            }
                        )
                        "schedule" -> ScheduleScreen()
                        "library" -> LibraryScreen()
                        "settings" -> SettingsScreen()
                    }
                }
            }
        }
    }
}

