/**
 * Animated curved navigation bar matching user specification:
 * - Floating circular active item with spring vertical translation
 * - Curved notch/bump in navigation bar following active item
 * - Unique accent color and stage ambient background per tab
 */
@Composable
fun AnimatedCurvedNavigationBar(
    tabs: List<TabItem>,
    selectedTabId: String,
    onTabSelected: (String) -> Unit
) {
    val activeIndex = tabs.indexOfFirst { it.id == selectedTabId }.coerceAtLeast(0)
    val activeTab = tabs[activeIndex]

    val barHeight = 64.dp
    val bumpHeight = 16.dp
    val bumpWidth = 84.dp

    BoxWithConstraints(
        modifier = Modifier
            .fillMaxWidth()
            .height(barHeight + bumpHeight)
    ) {
        val totalWidth = maxWidth
        val itemWidth = totalWidth / tabs.size

        // Calculate center X of the selected item in pixels
        val activeTargetFraction = (activeIndex + 0.5f) / tabs.size
        val animatedFraction by animateFloatAsState(
            targetValue = activeTargetFraction,
            animationSpec = spring(
                dampingRatio = 0.68f,
                stiffness = Spring.StiffnessMediumLow
            ),
            label = "bumpPosition"
        )

        // Draw curved bar background with SVG-like Bezier bump
        Canvas(modifier = Modifier.fillMaxSize()) {
            val canvasWidth = size.width
            val canvasHeight = size.height
            val centerX = canvasWidth * animatedFraction
            val bumpHeightPx = bumpHeight.toPx()
            val bumpWidthPx = bumpWidth.toPx()
            val barTopPx = bumpHeightPx

            val path = Path().apply {
                moveTo(0f, barTopPx)
                // Straight line to start of bump
                val bumpLeft = (centerX - bumpWidthPx / 2f).coerceAtLeast(0f)
                val bumpRight = (centerX + bumpWidthPx / 2f).coerceAtMost(canvasWidth)

                lineTo(bumpLeft, barTopPx)

                // Smooth cubic bezier curve rising to peak
                cubicTo(
                    bumpLeft + bumpWidthPx * 0.22f, barTopPx,
                    centerX - bumpWidthPx * 0.24f, 0f,
                    centerX, 0f
                )
                // Smooth cubic bezier curve descending from peak
                cubicTo(
                    centerX + bumpWidthPx * 0.24f, 0f,
                    bumpRight - bumpWidthPx * 0.22f, barTopPx,
                    bumpRight, barTopPx
                )

                lineTo(canvasWidth, barTopPx)
                lineTo(canvasWidth, canvasHeight)
                lineTo(0f, canvasHeight)
                close()
            }

            drawPath(path = path, color = Color(0xFF0C2018))
        }

        // Tab items
        Row(
            modifier = Modifier
                .fillMaxSize()
                .padding(top = bumpHeight),
            verticalAlignment = Alignment.CenterVertically
        ) {
            tabs.forEachIndexed { index, tab ->
                val isActive = index == activeIndex

                val elevationOffset by animateFloatAsState(
                    targetValue = if (isActive) -22f else 0f,
                    animationSpec = spring(
                        dampingRatio = 0.64f,
                        stiffness = Spring.StiffnessMediumLow
                    ),
                    label = "elevation"
                )

                val pastilleScale by animateFloatAsState(
                    targetValue = if (isActive) 1f else 0f,
                    animationSpec = spring(
                        dampingRatio = 0.68f,
                        stiffness = Spring.StiffnessMediumLow
                    ),
                    label = "scale"
                )

                Box(
                    modifier = Modifier
                        .weight(1f)
                        .fillMaxHeight()
                        .clickable(
                            interactionSource = remember { MutableInteractionSource() },
                            indication = null
                        ) { onTabSelected(tab.id) }
                        .testTag("tab_${tab.id}"),
                    contentAlignment = Alignment.Center
                ) {
                    Box(
                        modifier = Modifier
                            .offset(y = elevationOffset.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        // Floating round pastille behind active icon
                        if (pastilleScale > 0.05f) {
                            Box(
                                modifier = Modifier
                                    .size((48 * pastilleScale).dp)
                                    .shadow(8.dp, CircleShape)
                                    .clip(CircleShape)
                                    .background(tab.accentColor)
                            )
                        }

                        // Icon
                        Icon(
                            imageVector = tab.icon,
                            contentDescription = tab.label,
                            tint = if (isActive) Color.White else Color(0x99FFFFFF),
                            modifier = Modifier.size(24.dp)
                        )
                    }
                }
            }
        }
    }
}

