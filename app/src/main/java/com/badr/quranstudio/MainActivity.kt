@Composable
fun BadrQuranStudioApp() {
    var selectedTab by remember { mutableStateOf("home") }
    var totalGenerated by remember { mutableIntStateOf(22) }
    var currentSurah by remember { mutableIntStateOf(2) }
    var currentAyah by remember { mutableIntStateOf(30) }
    var isGenerating by remember { mutableStateOf(false) }
    var generationProgress by remember { mutableFloatStateOf(0f) }
    val scope = rememberCoroutineScope()

    val currentTab = APP_TABS.find { it.id == selectedTab } ?: APP_TABS[0]
    val animatedStageColor by animateColorAsState(
        targetValue = currentTab.stageColor,
        animationSpec = tween(500),
        label = "stageColor"
